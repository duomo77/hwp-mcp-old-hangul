// Regenerate from the public-domain KTUG table; no network access required.
// Usage: node scripts/generate-old-hangul-map.mjs /path/to/hypua2jamocomposed.txt
import { createHash } from "node:crypto";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";

const expectedSha = "118d90e18d53877ea8ee0034936ffcffd8d4fc0e88e8f7a27cd53fff6ff46585";
const source = readFileSync(process.argv[2]);
if (createHash("sha256").update(source).digest("hex") !== expectedSha) {
  throw new Error("Source checksum mismatch; see docs/old-hangul.md");
}
const entries = [];
const seen = new Set();
for (const line of source.toString("utf8").split(/\r?\n/)) {
  if (!line.startsWith("U+")) continue;
  const match = /^U\+([A-F0-9]+) =>((?: U\+[A-F0-9]+)*)\s*$/.exec(line.split("%%%", 1)[0]);
  if (!match) throw new Error(`Invalid mapping: ${line}`);
  const [, key, value] = match;
  // F86A has an empty mapping upstream. Preserve it instead of deleting text.
  if (!value.trim()) continue;
  if (seen.has(key)) throw new Error(`Duplicate mapping: ${key}`);
  seen.add(key);
  const escaped = [...value.matchAll(/U\+([A-F0-9]+)/g)]
    .map((m) => `\\u${m[1]}`).join("");
  entries.push(`  0x${key}: "${escaped}",`);
}
if (entries.length !== 5660) throw new Error("Expected 5,660 nonempty mappings");
const header = `// Generated by scripts/generate-old-hangul-map.mjs. Do not edit by hand.
// KTUG HanyangPuaTableProject data — Public Domain.
// Source, license declaration and SHA-256: docs/old-hangul.md
export const HANYANG_PUA: Readonly<Partial<Record<number, string>>> = Object.freeze({
`;
const out = new URL("../src/core/data/hanyang-pua.ts", import.meta.url);
mkdirSync(new URL("../src/core/data/", import.meta.url), { recursive: true });
writeFileSync(out, header + entries.join("\n") + "\n});\n");
console.log(`Generated ${entries.length} mappings`);
